package io.orderflow.inventory.repository;

import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Repository;
import software.amazon.awssdk.enhanced.dynamodb.DynamoDbEnhancedClient;
import software.amazon.awssdk.enhanced.dynamodb.DynamoDbIndex;
import software.amazon.awssdk.enhanced.dynamodb.DynamoDbTable;
import software.amazon.awssdk.enhanced.dynamodb.Key;
import software.amazon.awssdk.enhanced.dynamodb.TableSchema;
import software.amazon.awssdk.enhanced.dynamodb.model.Page;
import software.amazon.awssdk.enhanced.dynamodb.model.QueryConditional;
import software.amazon.awssdk.enhanced.dynamodb.model.TransactWriteItemsEnhancedRequest;

import io.orderflow.common.outbox.OutboxRecord;
import io.orderflow.common.outbox.OutboxRepository;
import io.orderflow.inventory.model.InventoryItem;
import io.orderflow.inventory.model.Reservation;

/**
 * Data access for {@code inventory} and {@code inventory_reservations}.
 *
 * <p>Both mutating paths are single {@code TransactWriteItems} calls that span stock counters, the
 * reservation record and the outbox row. That is what makes "stock held" and "InventoryReserved
 * will be published" the same fact rather than two facts that can disagree after a crash.
 */
@Repository
public class InventoryRepository {

    private final DynamoDbEnhancedClient enhancedClient;
    private final DynamoDbTable<InventoryItem> inventoryTable;
    private final DynamoDbTable<Reservation> reservationTable;
    private final DynamoDbIndex<Reservation> reservationsByOrder;
    private final OutboxRepository outboxRepository;

    public InventoryRepository(DynamoDbEnhancedClient enhancedClient,
                               OutboxRepository outboxRepository,
                               @Value("${app.dynamodb.tables.inventory:inventory}") String inventoryTableName,
                               @Value("${app.dynamodb.tables.reservations:inventory_reservations}")
                               String reservationsTableName) {
        this.enhancedClient = enhancedClient;
        this.inventoryTable = enhancedClient.table(inventoryTableName,
                TableSchema.fromBean(InventoryItem.class));
        this.reservationTable = enhancedClient.table(reservationsTableName,
                TableSchema.fromBean(Reservation.class));
        this.reservationsByOrder = reservationTable.index(Reservation.ORDER_INDEX);
        this.outboxRepository = outboxRepository;
    }

    /**
     * Loads the SKUs an order needs.
     *
     * <p>Deliberately individual {@code GetItem} calls rather than {@code BatchGetItem}: an order
     * touches a handful of SKUs, each read is a hot partition lookup, and batch semantics would
     * force us to handle {@code UnprocessedKeys} for no measurable gain at this cardinality.
     */
    public Map<String, InventoryItem> findBySkus(Collection<String> skus) {
        Map<String, InventoryItem> found = new LinkedHashMap<>();
        for (String sku : skus) {
            InventoryItem item = inventoryTable.getItem(Key.builder().partitionValue(sku).build());
            if (item != null) {
                found.put(sku, item);
            }
        }
        return found;
    }

    public void save(InventoryItem item) {
        inventoryTable.putItem(item);
    }

    /**
     * Applies the hold: decrements availability for every SKU, writes the reservation, and enqueues
     * {@code InventoryReserved} — all or nothing.
     *
     * <p>The per-item version conditions are generated by the enhanced client, so a concurrent
     * reservation for the same SKU cancels this transaction instead of overselling.
     */
    public void commitReservation(List<InventoryItem> updatedItems,
                                  Reservation reservation,
                                  OutboxRecord outboxRecord) {
        TransactWriteItemsEnhancedRequest.Builder request = TransactWriteItemsEnhancedRequest.builder()
                .addPutItem(reservationTable, reservation)
                .addPutItem(outboxRepository.table(), outboxRecord);
        updatedItems.forEach(item -> request.addPutItem(inventoryTable, item));
        enhancedClient.transactWriteItems(request.build());
    }

    /** Rejection path: no stock changes, only the {@code InventoryRejected} outbox row. */
    public void recordRejection(OutboxRecord outboxRecord) {
        outboxRepository.save(outboxRecord);
    }

    /**
     * Compensating write: give the held units back and flip the reservation to {@code RELEASED} in
     * one transaction, so a crash cannot leave stock returned but the reservation still held (which
     * would let a redelivery return it twice).
     */
    public void releaseReservation(List<InventoryItem> updatedItems, Reservation reservation) {
        TransactWriteItemsEnhancedRequest.Builder request = TransactWriteItemsEnhancedRequest.builder()
                .addPutItem(reservationTable, reservation);
        updatedItems.forEach(item -> request.addPutItem(inventoryTable, item));
        enhancedClient.transactWriteItems(request.build());
    }

    public Optional<Reservation> findReservation(String reservationId) {
        return Optional.ofNullable(reservationTable.getItem(
                Key.builder().partitionValue(reservationId).build()));
    }

    public Optional<Reservation> findReservationByOrderId(String orderId) {
        return reservationsByOrder
                .query(QueryConditional.keyEqualTo(Key.builder().partitionValue(orderId).build()))
                .stream()
                .map(Page::items)
                .flatMap(List::stream)
                .findFirst();
    }
}
